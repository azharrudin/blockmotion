import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({
  stdin: { contents: `export { useEditor, isValidProject, persistProject } from './src/editor/store';
    export { createProject } from './src/editor/presets';
    export { sampleObjectPose } from './src/editor/interpolation';
    export { timelineTracks } from './src/editor/tracks';
    export { StudioScene } from './src/engine/StudioScene';
    export * as THREE from 'three';`, resolveDir: process.cwd() },
  bundle: true, write: false, format: 'esm', platform: 'node',
});
const { useEditor, isValidProject, persistProject, createProject, sampleObjectPose, timelineTracks, StudioScene, THREE } = await import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64'));
const state = () => useEditor.getState();
const object = id => state().project.objects.find(o => o.id === id);
const pose = (x, rotation = 0, scale = 1) => ({ position: [x, 0, 0], rotation: [0, rotation, 0], scale: [scale, scale, scale] });
const saved = new Map();
globalThis.localStorage = { setItem: (key, value) => saved.set(key, value), getItem: key => saved.get(key) ?? null };
state().newProject();
state().addObject('tree');
const id = state().selectedObject;
assert.equal(object(id).keyframes.length, 1);
assert.equal(timelineTracks(state().project).at(-1).id, id);
const rig = structuredClone(state().project.tracks);
state().previewObjectPose(pose(0, 350));
state().commitKey();
state().seek(2);
state().setAutoKey(false);
state().previewObjectPose(pose(10, 10, 2));
state().commitObjectPose();
assert.equal(object(id).keyframes.length, 1, 'auto-key off leaves edit pending');
assert.deepEqual(state().objectPreview, pose(10, 10, 2));
state().commitKey();
assert.equal(object(id).keyframes.length, 2);
assert.equal(state().objectPreview, null);
assert.deepEqual(state().project.tracks, rig, 'keying objects does not touch the rig');
assert.deepEqual(sampleObjectPose(object(id), 1, 'linear'), pose(5, 360, 1.5));
assert.equal(sampleObjectPose(object(id), 0.5, 'smooth').position[0], 1.5625);
assert.equal(sampleObjectPose(object(id), 1, 'step').position[0], 0);
state().seek(1);
state().previewObjectPose(pose(6, -720, 1.4));
state().commitKey();
assert.equal(sampleObjectPose(object(id), 1, 'step').position[0], 6, 'step switches at exact intermediate key');
assert.equal(sampleObjectPose(object(id), 1.5, 'linear').rotation[1], -715, 'shortest rotation with large negative Euler values');
state().previewObjectPose(pose(7));
state().commitKey();
assert.equal(object(id).keyframes.length, 3, 'same-frame edit replaces key');
assert.equal(sampleObjectPose(object(id), 1, 'linear').position[0], 7);
state().undo();
assert.equal(sampleObjectPose(object(id), 1, 'linear').position[0], 6);
state().redo();
assert.equal(sampleObjectPose(object(id), 1, 'linear').position[0], 7);
const middle = object(id).keyframes.find(k => k.time === 1);
state().moveKey(id, middle.id, 1.5);
assert.equal(object(id).keyframes.find(k => k.id === middle.id).time, 1.5);
state().setSelectedKey({ node: id, id: middle.id });
assert.equal(state().selectedObject, id);
state().deleteKey();
assert.equal(object(id).keyframes.length, 2);
state().undo();
assert.equal(object(id).keyframes.length, 3);
state().moveKey(id, middle.id, 2);
assert.equal(object(id).keyframes.length, 2, 'moving onto another key replaces it');
state().undo();
const source = structuredClone(object(id));
state().duplicateObject();
const copy = object(state().selectedObject);
assert.notEqual(copy.id, source.id);
assert.equal(copy.keyframes.length, source.keyframes.length);
copy.keyframes.forEach((key, index) => {
  assert.notEqual(key.id, source.keyframes[index].id);
  assert.notEqual(key.value, source.keyframes[index].value);
  assert.equal(key.value.position[0], source.keyframes[index].value.position[0] + 2);
});
state().deleteObject();
assert.equal(timelineTracks(state().project).some(t => t.id === copy.id), false);
state().undo();
assert.equal(timelineTracks(state().project).some(t => t.id === copy.id), true);
state().selectObject(id);
state().seek(2);
state().setAutoKey(true);
const history = state().past.length;
state().previewObjectPose(pose(12, 90, 3));
state().previewObjectPose(pose(14, 90, 3));
assert.equal(state().past.length, history);
state().commitObjectPose();
assert.equal(state().past.length, history + 1, 'one history entry for auto-key drag');
state().updateSetting({ duration: 1 });
assert.ok(state().project.objects.every(o => o.keyframes.every(k => k.time <= 1)));
assert.equal(isValidProject(state().project), true);
state().undo();
assert.equal(object(id).keyframes.at(-1).time, 2);
state().updateSetting({ duration: 4 });
state().seek(4);
state().previewObjectPose(pose(20));
state().commitKey();
state().selectObject(state().project.objects[0].id);
state().preset('walk');
assert.equal(state().project.duration, 4, 'shorter rig preset preserves object animation duration');
assert.equal(object(id).keyframes.at(-1).time, 4);
assert.equal(isValidProject(state().project), true);
assert.equal(persistProject(state().project), true);
const exported = JSON.parse(saved.get('blockmotion-studio-project-v1'));
exported.objects.forEach(o => o.keyframes.reverse());
assert.equal(isValidProject(exported), true);
state().loadProject(exported);
assert.equal(object(id).keyframes[0].time, 0, 'object keys sorted on import');
assert.equal(state().objectPreview, null);

const studio = Object.create(StudioScene.prototype);
studio.scene = new THREE.Scene(); studio.assetNodes = new Map();
studio.controls = { object: null, detach() { this.object = null; } }; studio.draggingGizmo = false;
studio.syncSceneObjects();
state().seek(1);
studio.syncSceneObjects();
const rendered = studio.assetNodes.get(id).root;
const expected = sampleObjectPose(object(id), 1, state().project.interpolation);
assert.deepEqual(rendered.position.toArray(), expected.position);
state().seek(3);
studio.syncSceneObjects();
assert.equal(studio.assetNodes.get(id).root, rendered, 'scrubbing keeps geometry');
assert.notEqual(rendered.position.x, expected.position[0]);
state().selectObject(id);
state().previewObjectPose(pose(30));
studio.syncSceneObjects();
assert.equal(rendered.position.x, 30, 'pending manual edits render');
state().seek(3);
studio.syncSceneObjects();
assert.notEqual(rendered.position.x, 30, 'scrubbing discards pending edits');
state().seek(0); state().play(true); state().tick(1);
studio.syncSceneObjects();
assert.equal(rendered.position.x, expected.position[0], 'playback samples animation');
state().previewObjectPose(pose(8));
assert.equal(state().playing, false, 'editing pauses playback');
state().seek(0);

const base = createProject('Legacy static objects');
const legacy = { ...base, objects: [{ id: 'obj_legacy', kind: 'store', name: 'Legacy store', color: '#aabbcc', pose: pose(3) }] };
assert.equal(isValidProject(legacy), true);
state().loadProject(legacy);
state().selectObject('obj_legacy'); state().seek(2); state().previewObjectPose(pose(9)); state().commitKey();
assert.deepEqual(object('obj_legacy').keyframes.map(k => [k.time, k.value.position[0]]), [[0, 3], [2, 9]], 'first legacy key preserves frame-zero placement');
for (const keys of [null, [{ id: 'bad', time: NaN, value: pose(1) }], [{ id: 'bad', time: 5, value: pose(1) }], [{ id: 'bad', time: 1, value: pose(1, 0, -1) }], [{ id: 'same', time: 0, value: pose(1) }, { id: 'same', time: 1, value: pose(2) }], [{ id: 'one', time: 0, value: pose(1) }, { id: 'two', time: 0, value: pose(2) }]]) {
  assert.equal(isValidProject({ ...legacy, objects: [{ ...legacy.objects[0], keyframes: keys }] }), false);
}
for (const key of [...object('obj_legacy').keyframes]) { state().setSelectedKey({ node: 'obj_legacy', id: key.id }); state().deleteKey(); }
assert.deepEqual(sampleObjectPose(object('obj_legacy'), 2, 'linear'), pose(3), 'empty track falls back to stored placement');
state().loadProject(base); studio.syncSceneObjects();
console.log('PASS: object keyframes, manual/auto-key, interpolation including step boundaries, track selection/move/delete, animation duplication, duration/preset preservation, import/export, legacy migration, playback and renderer sampling.');
